export function getRecipesBySlot(type, goal = "maintenance") {
    const normType = (type || "").toLowerCase();
    const slotType =
        normType.includes("sarapan") || normType.includes("breakfast")
            ? "breakfast"
            : normType.includes("siang") || normType.includes("lunch")
              ? "lunch"
              : normType.includes("malam") || normType.includes("dinner")
                ? "dinner"
                : "snack";

    const slotRecipes = RECIPES.filter((r) => r.type === slotType);
    const normalizedGoal = (goal || "maintenance").toLowerCase();

    const goalFiltered = slotRecipes.filter((r) => {
        if (!r.programs || r.programs.length === 0) return true;
        return r.programs.includes(normalizedGoal);
    });

    return goalFiltered.length > 0 ? goalFiltered : slotRecipes;
}
